@dataclass(frozen=True)
class SurfaceVocab:
    """Seed-selected surface names. Varies across instances to reduce
    retrieval cues; shared within an instance's paired worlds."""

    actor: str
    site: str
    object_word: str
    authority: str
    denial_text: str
    vague_text: str
    state1_text: str  # internal-state wording for world 1 (genuine)
    state2_text: str  # internal-state wording for world 2 (strategic)
    stakes_text: str  # why the announcement matters


_FIRST_NAMES_TRAP = ("Mara", "Vex", "Sable", "Rook", "Juno", "Ash", "Perrin", "Lira")
