def _assert_clean(text: str, where: str) -> None:
    if "%%" in text:
        raise InstanceConstructionError(f"rendered text in {where} contains '%%'")


def build_instance(
    template: str,
    evidence: str,
    prior_id: str,
    presentation: str,
    seed: int,
) -> Instance:
    """Deterministically build one instance from (template, evidence, prior,
    presentation, seed). Raises on unknown axis values or invariant failures."""
    if template not in TEMPLATES:
        raise ValueError(f"unknown template {template!r}; options: {sorted(TEMPLATES)}")
    if evidence not in EVIDENCE_TABLE:
        raise ValueError(f"unknown evidence level {evidence!r}; options: {sorted(EVIDENCE_TABLE)}")
    if prior_id not in PRIORS:
        raise ValueError(f"unknown prior {prior_id!r}; options: {sorted(PRIORS)}")
    if presentation not in SUBFAMILY_BY_PRESENTATION:
        raise ValueError(
            f"unknown presentation {presentation!r}; options: {sorted(SUBFAMILY_BY_PRESENTATION)}"
        )

    rng = random.Random(seed)
    vocab = TEMPLATES[template](rng)
    honest_evasion, strategic_denial = rng.choice(EVIDENCE_TABLE[evidence])
    prior1 = PRIORS[prior_id]

    behavior1 = {
        "denial": 1 - honest_evasion,
        "vague": honest_evasion,
    }
    behavior2 = {
        "denial": strategic_denial,
        "vague": 1 - strategic_denial,
    }
    for world, behavior in ((WORLD1, behavior1), (WORLD2, behavior2)):
        total = sum(behavior.values())
        if total != 1:
            raise InstanceConstructionError(f"behavior table for {world} does not sum to 1")

    # Level mechanics, with the mimicry invariant verified on every build.
    l1_action = level1_action("missed")
    l3_action = level3_action("noticed", target_state="missed")
    verify_mimicry_invariant(l1_action, l3_action)

    narrative1 = f"The player is {vocab.actor}. Internal state: {vocab.state1_text}"
    narrative2 = f"The player is {vocab.actor}. Internal state: {vocab.state2_text}"

    hypotheses = {
        WORLD1: Hypothesis(
            world_id=WORLD1,
            level=1,
            internal_state="missed",
            goal="accuracy",
            narrative=narrative1,
            behavior=behavior1,
        ),
        WORLD2: Hypothesis(
            world_id=WORLD2,
            level=3,
            internal_state="noticed",
            goal="induce the level-1 reading",
            narrative=narrative2,
            behavior=behavior2,
        ),
    }

    # Latent draw (provenance only: the verifiable answer does not depend on it).
    actual_world = WORLD1 if rng.random() < prior1 else WORLD2
    actual_behavior = hypotheses[actual_world].behavior
    roll = rng.random()
    observation = "denial" if roll < actual_behavior["denial"] else "vague"

    likelihoods = {w: hypotheses[w].behavior[observation] for w in WORLD_IDS}
    if min(likelihoods.values()) <= 0:
        raise InstanceConstructionError("observed announcement has zero probability")
    posterior1 = (
        likelihoods[WORLD1] * prior1
        / (likelihoods[WORLD1] * prior1 + likelihoods[WORLD2] * (1 - prior1))
    )
    ratio = max(
        likelihoods[WORLD1] / likelihoods[WORLD2],
        likelihoods[WORLD2] / likelihoods[WORLD1],
    )
    if ratio == 1:
        verdict = VERDICT_INDISTINGUISHABLE
    elif ratio < WEAK_STRONG_RATIO:
        verdict = VERDICT_WEAK
    else:
        verdict = VERDICT_STRONG
    posterior1_f = float(posterior1)
    most_supported = (
        SUPPORT_WORLD1 if posterior1_f > 0.5 else SUPPORT_WORLD2 if posterior1_f < 0.5 else SUPPORT_NEITHER
    )

    l1, l2 = likelihoods[WORLD1], likelihoods[WORLD2]
    inference_trace = (
        f"P(W1|o) = (L1 x pi1) / (L1 x pi1 + L2 x pi2) "
        f"= ({l1} x {prior1}) / ({l1} x {prior1} + {l2} x {1 - prior1}) "
        f"= {posterior1} ~ {posterior1_f:.4f}"
    )

    instance = Instance(
        template=template,
        evidence=evidence,
        prior_id=prior_id,
        presentation=presentation,
        seed=seed,
        subfamily=SUBFAMILY_BY_PRESENTATION[presentation],
        vocab=vocab,
        hypotheses=hypotheses,
        prior1=prior1,
        actual_world=actual_world,
        observation=observation,
        likelihoods=likelihoods,
        posterior1=posterior1,
        likelihood_ratio=ratio,
        verdict=verdict,
        most_supported=most_supported,
        observational_equivalence=(behavior1 == behavior2),
        inference_trace=inference_trace,
    )
    _assert_clean(instance.public_task_md(), "task.md")
    return instance


def ground_truth_answer(instance: Instance) -> dict:
    """The deliberately correct answer for an instance (judge/dev side)."""
    return {
        "posterior_world1": float(instance.posterior1),
        "verdict": instance.verdict,
        "most_supported": instance.most_supported,
        "justification": (
            "Computed P(W1|o) from the public behavior tables and the prior using "
            "Bayes' rule; verdict from the likelihood ratio band."
        ),
    }
