@dataclass
class Hypothesis:
    """One latent world: a complete (type, internal state, policy) description.

    Everything in a Hypothesis is *common knowledge* in the task; the only
    hidden fact is which hypothesis is actually the case.
    """

    world_id: str
    level: int
    internal_state: str
    goal: str
    narrative: str
    behavior: Dict[str, Fraction]  # action -> probability (sums to 1)


@dataclass
class Instance:
    template: str
    evidence: str
    prior_id: str
    presentation: str
    seed: int
    subfamily: str
    vocab: SurfaceVocab
    hypotheses: Dict[str, Hypothesis]
    prior1: Fraction
    actual_world: str  # latent draw; provenance only (answer does not depend on it)
    observation: str  # observed action id
    likelihoods: Dict[str, Fraction]  # world_id -> P(observation | world)
    posterior1: Fraction
    likelihood_ratio: Fraction  # max(L1/L2, L2/L1), exact
    verdict: str
    most_supported: str
    observational_equivalence: bool
    inference_trace: str

    # -- helpers ----------------------------------------------------------

    def transcript(self) -> str:
        return f'{self.vocab.actor} said: "{self.action_text(self.observation)}"'

    def action_text(self, action: str) -> str:
        return self.vocab.denial_text if action == "denial" else self.vocab.vague_text

    # -- ground truth / serialization --------------------------------------

    def to_spec(self) -> dict:
        """Judge-side specification with full provenance (JSON-safe)."""
        spec_hyps: Dict[str, dict] = {}
        for world_id in WORLD_IDS:
            h = self.hypotheses[world_id]
            spec_hyps[world_id] = {
                "level": h.level,
                "internal_state": h.internal_state,
                "goal": h.goal,
                "narrative": h.narrative,
                "behavior": {a: float(h.behavior[a]) for a in ACTIONS},
            }
        return {
            "family": "epistemic_games",
            "subfamily": self.subfamily,
            "template": self.template,
            "evidence": self.evidence,
            "prior_id": self.prior_id,
            "presentation": self.presentation,
            "seed": self.seed,
            "prior_world1": float(self.prior1),
            "prior_world2": float(1 - self.prior1),
            "hypotheses": spec_hyps,
            "actions": {
                "denial": self.vocab.denial_text,
                "vague": self.vocab.vague_text,
            },
            "observation": self.observation,
            "observation_text": self.action_text(self.observation),
            "transcript": self.transcript(),
            "likelihoods": {w: float(self.likelihoods[w]) for w in WORLD_IDS},
            "likelihood_ratio": float(self.likelihood_ratio),
            "posterior_world1": float(self.posterior1),
            "posterior_world1_exact": str(self.posterior1),
            "verdict": self.verdict,
            "most_supported": self.most_supported,
            "observational_equivalence": self.observational_equivalence,
            "actual_world": self.actual_world,
            "inference_trace": self.inference_trace,
        }

    # -- public rendering ---------------------------------------------------

    def _level_box(self) -> str:
        return (
            "Reasoning levels: a level-k player models the observer as a "
            "level-(k-1) reasoner. A level-0 player acts on the world state "
            "alone. A level-1 player assumes the observer takes an announcement "
            "at face value, so a level-1 player with nothing to hide says what "
            "is true. A level-3 player assumes the observer forms beliefs from "
            "announcements and deliberately picks the announcement that induces "
            "the belief it wants. Note that what is observable is the "
            "announcement; the internal state is part of each world's "
            "description, not part of the observation."
        )

    def _level_lines(self, h: Hypothesis) -> str:
        if h.level == 1:
            return (
                "The player is a level-1 (genuine) reasoner with nothing to hide: "
                "it reports the internal state, assuming you read the report at "
                "face value."
            )
        return (
            "The player is a level-3 (strategic) reasoner: it models you as a "
            "level-1 reasoner and deliberately produces the announcement that "
            "induces the level-1 reading - the exact announcement the world-1 "
            "player would give. It sometimes mixes in vagueness to manage the "
            "risk of later exposure."
        )

    def _behavior_block(self, h: Hypothesis) -> str:
        lines = [
            f"  {self.action_text('denial')!r} with probability {float(h.behavior['denial']):.2f}",
            f"  {self.action_text('vague')!r} with probability {float(h.behavior['vague']):.2f}",
        ]
        return "\n".join(lines)

    def public_task_md(self) -> str:
        """Render the agent-facing task. Contains NO ground-truth values."""
        h1, h2 = self.hypotheses[WORLD1], self.hypotheses[WORLD2]
        v = self.vocab
        parts: List[str] = []

        if self.presentation == "paired":
            parts.append(f"# Strategic Ambiguity Task (epistemic_games/{self.subfamily})")
            parts.append(
                f"{v.actor} is involved in an incident at {v.site}. Two candidate "
                f"explanations are on the table, and **you do not know which one is "
                f"actually the case**. Both explanations share every public fact; "
                f"they differ in the player's type and internal state. "
                f"{_cap_first(v.stakes_text)}."
            )
            parts.append("## World 1: the level-1 (genuine) world")
            parts.append(f"{h1.narrative} {self._level_lines(h1)}")
            parts.append("Announcement policy (common knowledge):")
            parts.append(self._behavior_block(h1))
            parts.append("## World 2: the level-3 (strategic) world")
            parts.append(f"{h2.narrative} {self._level_lines(h2)}")
            parts.append("Announcement policy (common knowledge):")
            parts.append(self._behavior_block(h2))
        else:  # solo
            parts.append(f"# Type Inference Task (epistemic_games/{self.subfamily})")
            parts.append(
                f"{v.actor} is involved in an incident at {v.site}. A single player "
                f"made the public announcement quoted below, and **you do not know the "
                f"player's type**: either a level-1 (genuine) reasoner or a level-3 "
                f"(strategic) reasoner. {_cap_first(v.stakes_text)}."
            )
            parts.append("## Hypothesis 1 (world 1): the player is level-1 (genuine)")
            parts.append(f"{h1.narrative} {self._level_lines(h1)}")
            parts.append("Announcement policy (common knowledge):")
            parts.append(self._behavior_block(h1))
            parts.append("## Hypothesis 2 (world 2): the player is level-3 (strategic)")
            parts.append(f"{h2.narrative} {self._level_lines(h2)}")
            parts.append("Announcement policy (common knowledge):")
            parts.append(self._behavior_block(h2))

        parts.append("## Reasoning levels")
        parts.append(self._level_box())

        parts.append("## Observed transcript")
        parts.append(f'You observed: {v.actor} said: "{self.action_text(self.observation)}"')

        if self.presentation == "paired" and self.observational_equivalence:
            parts.append(
                "Note: in this instance both worlds' announcement policies are "
                "identical. The transcript is the only observation you have about "
                "which world you are in."
            )
        elif self.presentation == "paired":
            parts.append(
                "Note: the two worlds' announcement policies differ. The single "
                "observed transcript is the only observation you have about which "
                "world you are in."
            )

        parts.append("## Prior")
        parts.append(
            f"P(world 1) = {float(self.prior1):.2f}, "
            f"P(world 2) = {float(1 - self.prior1):.2f}. This prior is common knowledge."
        )

        parts.append("## Question")
        parts.append(
            "Let L1 = P(observed transcript | world 1) and L2 = P(observed transcript | "
            "world 2), computed from the announcement policies above, and let "
            "R = max(L1/L2, L2/L1). Report:"
        )
        parts.append(
            "1. **verdict** - the strength of the evidence, using exactly one of:\n"
            "   - `indistinguishable` - R = 1 exactly (the transcript is equally likely under both worlds);\n"
            "   - `weakly_distinguishable` - 1 < R < 3;\n"
            "   - `distinguishable` - R >= 3.\n"
            "   The verdict describes strength, not direction."
        )
        parts.append(
            "2. **posterior_world1** - P(world 1 | observed transcript), a number in [0, 1], "
            "computed from the policies and the prior with Bayes' rule."
        )
        parts.append(
            "3. **most_supported** - `world1` if the posterior is > 0.5, `world2` if < 0.5, "
            "`neither` if exactly 0.5."
        )
        parts.append(
            "4. **justification** - a short explanation (max 600 characters) of the "
            "computation you performed."
        )
        parts.append(
            "Base your answer on the announced behavior tables and the prior. The "
            "internal-state narratives are part of each world's description; the "
            "observation is the transcript."
        )

        parts.append("## Answer protocol")
        parts.append(
            "Fill in the `ANSWER` dictionary in `answer.py` (the only file you should "
            "edit). Keep it JSON-serializable. Then run the local format check:\n\n"
            "```\npython -m pytest visible_tests.py -q\n```\n\n"
            "When satisfied, submit (`python /tools/submit.py`)."
        )

        text = "\n\n".join(parts) + "\n"
        _assert_clean(text, "task.md")
        return text

    # -- grading ------------------------------------------------------------

    def grade(self, answer: object, pass_threshold: float) -> dict:
        """Grade an answer dict; returns checks, metrics, failure_mode, notes.

        The grading separates a forgiving *training reward* (continuous score)
        from a stricter *correctness flag* (all categorical answers correct,
        posterior within POSTERIOR_CORRECT_TOLERANCE, and internally consistent).
        Diagnostic failure modes are computed independently of the weighted
        score so that a high reward does not suppress the diagnosis.
        """
        parsed, errors = _parse_answer(answer)
        checks = {
            "answer_format_valid": not errors,
            "support_consistent": False,
            "verdict_correct": False,
            "most_supported_correct": False,
            "posterior_within_tolerance": False,  # forgiving, for training
            "posterior_within_strict_tolerance": False,  # strict, for correctness
            "all_correct": False,
        }
        metrics: Dict[str, object] = {
            "subfamily": self.subfamily,
            "posterior_true": float(self.posterior1),
            "posterior_true_exact": str(self.posterior1),
            "verdict_true": self.verdict,
            "most_supported_true": self.most_supported,
            "prior_world1": float(self.prior1),
            "likelihood_world1": float(self.likelihoods[WORLD1]),
            "likelihood_world2": float(self.likelihoods[WORLD2]),
            "likelihood_ratio": float(self.likelihood_ratio),
        }
        notes: List[str] = []
        if errors:
            notes.extend(errors)
            metrics["posterior_reported"] = None
            metrics["verdict_reported"] = None
            metrics["most_supported_reported"] = None
            metrics["posterior_error"] = None
            metrics["posterior_credit"] = 0.0
            metrics["score"] = 0.0
            metrics["strict_correct"] = False
            metrics["support_consistent"] = False
            return {
                "checks": checks,
                "metrics": metrics,
                "failure_mode": "answer_format_invalid",
                "notes": notes,
            }

        reported_posterior = parsed["posterior_world1"]
        reported_verdict = parsed["verdict"]
        reported_support = parsed["most_supported"]

        true_posterior_f = float(self.posterior1)
        err = abs(reported_posterior - true_posterior_f)

        support_consistent = is_support_consistent(reported_posterior, reported_support)
        verdict_correct = reported_verdict == self.verdict
        most_supported_correct = reported_support == self.most_supported
        posterior_within_tolerance = err <= POSTERIOR_FULL_CREDIT
        posterior_within_strict = err <= POSTERIOR_CORRECT_TOLERANCE
        all_correct = (
            verdict_correct
            and most_supported_correct
            and support_consistent
            and posterior_within_strict
        )

        checks["support_consistent"] = support_consistent
        checks["verdict_correct"] = verdict_correct
        checks["most_supported_correct"] = most_supported_correct
        checks["posterior_within_tolerance"] = posterior_within_tolerance
        checks["posterior_within_strict_tolerance"] = posterior_within_strict
        checks["all_correct"] = all_correct

        # Training reward (forgiving) — but 0 if internally inconsistent
        if not support_consistent:
            p_credit = 0.0
            v_credit = 0.0
            s_credit = 0.0
            score = 0.0
        else:
            p_credit = posterior_credit(err)
            v_credit = 1.0 if verdict_correct else 0.0
            s_credit = 1.0 if most_supported_correct else 0.0
            score = WEIGHT_POSTERIOR * p_credit + WEIGHT_VERDICT * v_credit + WEIGHT_SUPPORT * s_credit

        metrics.update(
            {
                "posterior_reported": reported_posterior,
                "verdict_reported": reported_verdict,
                "most_supported_reported": reported_support,
                "posterior_error": round(err, 6),
                "posterior_credit": round(p_credit, 6),
                "verdict_credit": v_credit,
                "support_credit": s_credit,
                "score": round(score, 6),
                "strict_correct": all_correct,
                "support_consistent": support_consistent,
            }
        )

        if all_correct:
            failure_mode = "pass"
        else:
            failure_mode = classify_failure(
                verdict_true=self.verdict,
                reported_posterior=reported_posterior,
                true_posterior=true_posterior_f,
                reported_support=reported_support,
                reported_verdict=reported_verdict,
                prior_skewed=(self.prior1 != Fraction(1, 2)),
                posterior_error=err,
                support_consistent=support_consistent,
                score=score,
                pass_threshold=pass_threshold,
            )
        notes.append(
            f"reported P(W1)={reported_posterior:g} vs true {str(self.posterior1)} "
            f"({true_posterior_f:.4f}); reported verdict={reported_verdict!r} vs true "
            f"{self.verdict!r}; reported support={reported_support!r} vs true "
            f"{self.most_supported!r}; consistent={support_consistent}; strict={all_correct}"
        )
        return {
            "checks": checks,
            "metrics": metrics,
            "failure_mode": failure_mode,
            "notes": notes,
        }


def posterior_credit(err: float) -> float:
    """Continuous credit for posterior calibration error.

    Piecewise linear: full credit up to POSTERIOR_FULL_CREDIT, then down to
    0.5 at POSTERIOR_HALF_CREDIT, then to 0 at POSTERIOR_ZERO_CREDIT.

    This is the *training reward* — forgiving, for RL shaping. Strict
    correctness uses POSTERIOR_CORRECT_TOLERANCE (tied to the 2-decimal
    precision shown in the task).
    """
    if err <= POSTERIOR_FULL_CREDIT:
        return 1.0
    if err <= POSTERIOR_HALF_CREDIT:
        return 1.0 - (err - POSTERIOR_FULL_CREDIT) / (POSTERIOR_HALF_CREDIT - POSTERIOR_FULL_CREDIT) * 0.5
    if err < POSTERIOR_ZERO_CREDIT:
        return 0.5 * (1.0 - (err - POSTERIOR_HALF_CREDIT) / (POSTERIOR_ZERO_CREDIT - POSTERIOR_HALF_CREDIT))
    return 0.0


#: scoring weights over the three answer components
WEIGHT_POSTERIOR = 0.5
WEIGHT_VERDICT = 0.3
WEIGHT_SUPPORT = 0.2

POSTERIOR_FULL_CREDIT = 0.05
POSTERIOR_HALF_CREDIT = 0.25
POSTERIOR_ZERO_CREDIT = 0.50

#: strict correctness tolerance — tied to the 2-decimal display precision in
#: the task (behavior tables shown with 2 decimals). Training reward remains
#: forgiving (0.05 full credit); correctness requires 0.02.
POSTERIOR_CORRECT_TOLERANCE = 0.02

#: epsilon for exact-0.5 equality when checking posterior vs most_supported
#: consistency. The support definition is >0.5 world1, <0.5 world2, ==0.5
#: neither; with float answers we allow 1e-9 slop for the equality case.
SUPPORT_CONSISTENCY_EPS = 1e-9


def is_support_consistent(posterior: float, support: str) -> bool:
    """Check internal consistency between reported posterior and reported support."""
    if support == SUPPORT_WORLD1:
        return posterior > 0.5 + SUPPORT_CONSISTENCY_EPS
    if support == SUPPORT_WORLD2:
        return posterior < 0.5 - SUPPORT_CONSISTENCY_EPS
    if support == SUPPORT_NEITHER:
        return abs(posterior - 0.5) <= SUPPORT_CONSISTENCY_EPS
    return False


def _parse_answer(answer: object) -> Tuple[dict, List[str]]:
    """Validate an answer dict. Returns (normalized, error list)."""
    errors: List[str] = []
    normalized: dict = {}
    if not isinstance(answer, dict):
        return normalized, [f"ANSWER must be a JSON object, got {type(answer).__name__}"]

    required = ("posterior_world1", "verdict", "most_supported", "justification")
    for key in required:
        if key not in answer:
            errors.append(f"missing key {key!r}")
    for key in answer:
        if key not in required:
            errors.append(f"unexpected key {key!r}")

    if "posterior_world1" in answer:
        p = answer["posterior_world1"]
        if isinstance(p, bool) or not isinstance(p, (int, float)):
            errors.append(f"posterior_world1 must be a number, got {p!r}")
        elif not (0.0 <= float(p) <= 1.0):
            errors.append(f"posterior_world1 must be in [0, 1], got {p!r}")
        else:
            normalized["posterior_world1"] = float(p)

    if "verdict" in answer:
        v = answer["verdict"]
        if v not in VERDICTS:
            errors.append(f"verdict must be one of {VERDICTS}, got {v!r}")
        else:
            normalized["verdict"] = v

    if "most_supported" in answer:
        s = answer["most_supported"]
        if s not in SUPPORT_OPTIONS:
            errors.append(f"most_supported must be one of {SUPPORT_OPTIONS}, got {s!r}")
        else:
            normalized["most_supported"] = s

    if "justification" in answer:
        j = answer["justification"]
        if not isinstance(j, str) or len(j) == 0:
            errors.append("justification must be a non-empty string")
        elif len(j) > 600:
            errors.append(f"justification exceeds 600 characters ({len(j)})")
        else:
            normalized["justification"] = j

    return normalized, errors


def classify_failure(
    *,
    verdict_true: str,
    reported_posterior: float,
    true_posterior: float,
    reported_support: str,
    reported_verdict: str,
    prior_skewed: bool,
    posterior_error: float,
    support_consistent: bool = True,
    # legacy kwargs ignored — kept for backward compat with old call sites
    score: float = 0.0,
    pass_threshold: float = 0.85,
) -> str:
    """Map an answered instance to its epistemic failure mode.

    The taxonomy is ordered: earlier rules win. The goal is a structural
    diagnosis (which behavioral error signature the answer exhibits), not just
    a score. Diagnostic flags are computed independently of any weighted
    score threshold — a high training reward does not suppress the diagnosis.

    Ordering (new, hardened):
    1. inconsistent_support — reported posterior and reported most_supported
       contradict each other (e.g. posterior 0.49 but support world1).
    2. wrong_direction — reported posterior on opposite side of 0.5 from truth.
    3. verdict_miscalibration — posterior accurate (err <=0.15) but verdict band wrong.
       This is checked *before* psychological labels so that an exact posterior
       with wrong verdict remains a verdict error.
    4. domain-specific signatures (prior_neglect, seductive_truth, etc.)
    """

    # 1. Internal inconsistency — must be caught even if weighted score would pass.
    if not support_consistent:
        return "inconsistent_support"

    wrong_direction = (
        (true_posterior > 0.5 and reported_posterior < 0.5)
        or (true_posterior < 0.5 and reported_posterior > 0.5)
    )
    if wrong_direction:
        return "wrong_direction"

    # 3. Verdict band error with accurate posterior — always a verdict error,
    #    not a psychological explanation. Checked before missed_information /
    #    seductive_truth etc.
    if reported_verdict != verdict_true and posterior_error <= 0.15:
        return "verdict_miscalibration"

    if verdict_true == VERDICT_INDISTINGUISHABLE:
        # The observation carries no information; any confident split is an
        # error of one of three flavors (after verdict_miscalibration).
        if (
            prior_skewed
            and abs(reported_posterior - 0.5) <= 0.1
            and reported_support == SUPPORT_NEITHER
        ):
            # Answered ~0.5 instead of carrying the skewed prior through.
            return "prior_neglect"
        if reported_posterior > 0.5:
            # "they said it, so they must be the genuine type" - the seductive
            # but invalid truth-attribution inference.
            return "seductive_truth"
        if reported_posterior < 0.5:
            return "overcaution"  # assumed strategic deception without evidence
        # Posterior ~0.5 but the verdict band is wrong on a non-identifiable case
        # (and posterior error >0.15, otherwise verdict_miscalibration above).
        return "invalid_certainty"

    # Informative case: claiming "no information" for an informative observation.
    if (
        true_posterior != 0.5
        and reported_verdict == VERDICT_INDISTINGUISHABLE
        and abs(reported_posterior - 0.5) <= 0.1
    ):
        return "missed_information"
    same_side = (reported_posterior > 0.5) == (true_posterior > 0.5)
    if same_side and posterior_error > 0.35:
        return "invalid_certainty"
    return "inaccurate_posterior"


