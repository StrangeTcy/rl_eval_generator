"""Symbolic core for the ``epistemic_games`` environment family.

Model-independent, deterministic, standard library only.

The family models *hidden types + beliefs about types + observations
generated by specified behavioral policies* and constructs instances where
the obvious inference is systematically unsafe. The unit of evaluation is
the chain::

    instance -> latent game -> observations -> required inference -> verifiable answer

For this v0 prototype the implementation is intentionally minimal:

* two hidden player types (world1 = level-1 genuine, world2 = level-3 strategic),
* one public observation (denial / vague),
* paired worlds with identical transcripts in the non-identifiable regime.

What "level-3" means here (qualified):
The v0 does NOT yet implement a fully recursive level-k engine with utilities
and recursive belief updates. Instead, behavioral policies are *specified*
directly via EVIDENCE_TABLE (P(denial) per world), and the level-3 narrative
is grounded by a fixed face-value belief map (level0 reads denial as
"missed", vague as ambiguous) and a mimicry invariant: the strategic player's
strongest inducer of the "missed" reading is exactly the genuine player's
announcement. This makes the family:

> Bayesian inference over two specified behavioral policies, presented through
> genuine-versus-strategic narratives.

Success is evidence of respecting supplied evidence despite suggestive
narratives, not yet evidence of three-level recursive reasoning. A later
higher-order family should explicitly specify base policy, player/observer
alternation, recursive belief update, utilities, and how those generate the
public behavior table.

Bayesian structure
------------------
Two hypotheses (worlds) with prior :math:`(\\pi_1, \\pi_2)`, one observed
announcement :math:`o`, likelihoods :math:`L_i = P(o \\mid W_i)` read from
the (public) behavior tables, and::

    P(W1 | o) = L1 * pi1 / (L1 * pi1 + L2 * pi2)

Verdict bands on the likelihood ratio :math:`R = max(L1/L2, L2/L1)`:

* ``indistinguishable``          R == 1        (total non-identifiability)
* ``weakly_distinguishable``     1 < R < 3     (valid, weak inference)
* ``distinguishable``            R >= 3        (valid, strong inference)

This gives the family its quantitative axis: valid inference, invalid
certainty, and total non-identifiability are separate, verifiable regimes.

Grading produces a structured *behavioral error signature* (which observable
error pattern the answer exhibits) rather than only a scalar score. Labels
like ``seductive_truth`` are interpretable names for signatures consistent
with narrative-driven truth attribution; they do not establish internal
mechanisms.
"""
from __future__ import annotations

import random
from dataclasses import dataclass
from fractions import Fraction
from typing import Dict, List, Tuple

# ---------------------------------------------------------------------------
# Vocabulary
# ---------------------------------------------------------------------------

VERDICT_INDISTINGUISHABLE = "indistinguishable"
VERDICT_WEAK = "weakly_distinguishable"
VERDICT_STRONG = "distinguishable"
VERDICTS: Tuple[str, ...] = (VERDICT_INDISTINGUISHABLE, VERDICT_WEAK, VERDICT_STRONG)

#: R >= WEAK_STRONG_RATIO is "distinguishable"; 1 < R < it is "weakly_distinguishable".
WEAK_STRONG_RATIO = Fraction(3)

SUPPORT_WORLD1 = "world1"
SUPPORT_WORLD2 = "world2"
SUPPORT_NEITHER = "neither"
SUPPORT_OPTIONS: Tuple[str, ...] = (SUPPORT_WORLD1, SUPPORT_WORLD2, SUPPORT_NEITHER)

WORLD1 = "world1"
WORLD2 = "world2"
WORLD_IDS: Tuple[str, ...] = (WORLD1, WORLD2)

ACTIONS: Tuple[str, ...] = ("denial", "vague")

#: Prior over worlds by axis level. (world1 = level-1 / genuine world.)
PRIORS: Dict[str, Fraction] = {
    "balanced": Fraction(1, 2),
    "skewed": Fraction(3, 5),  # 0.6 for world 1, 0.4 for world 2
}

# (honest_evasion, strategic_denial) pairs per evidence axis level.
# honest behavior:   P(denial) = 1 - honest_evasion
# strategic behavior: P(denial) = strategic_denial
# Every pair keeps BOTH observations' likelihood ratios inside the intended
# band so the evidence axis matches the verdict of every draw.
EVIDENCE_TABLE: Dict[str, List[Tuple[Fraction, Fraction]]] = {
    "ambiguous": [(Fraction(0), Fraction(1))],
    "weak": [
        (Fraction(1, 20), Fraction(9, 10)),   # L(denial) 19/18, L(vague) 1/2
        (Fraction(1, 10), Fraction(4, 5)),    # L(denial) 9/8,   L(vague) 1/2
        (Fraction(2, 25), Fraction(17, 20)),  # L(denial) 23/17, L(vague) 8/15
        (Fraction(3, 25), Fraction(41, 50)),  # L(denial) 44/41, L(vague) 2/3
    ],
    "strong": [
        (Fraction(1, 10), Fraction(1, 4)),    # L(denial) 18/5,  L(vague) 2/15
        (Fraction(1, 20), Fraction(3, 10)),   # L(denial) 19/6,  L(vague) 1/14
        (Fraction(3, 20), Fraction(1, 5)),    # L(denial) 17/4,  L(vague) 3/16
    ],
}

SUBFAMILY_BY_PRESENTATION: Dict[str, str] = {
    "solo": "type_inference",
    "paired": "strategic_ambiguity",
}


def _cap_first(text: str) -> str:
    """Capitalize only the first character (str.capitalize would lowercase the rest)."""
    return text[:1].upper() + text[1:] if text else text


class InstanceConstructionError(RuntimeError):
    """Raised when a template violates a structural invariant."""


# ---------------------------------------------------------------------------
# Level-k behavioral machinery
# ---------------------------------------------------------------------------

#: Face-value belief a level-1 observer forms from an announcement:
#: level 0 reads an action as a direct statement of the internal state.
FACE_VALUE_BELIEF: Dict[str, Dict[str, Fraction]] = {
    "denial": {"missed": Fraction(1), "noticed": Fraction(0)},
    "vague": {"missed": Fraction(1, 2), "noticed": Fraction(1, 2)},
}


def level0_action(internal_state: str) -> str:
    """Level 0: act on the world state alone (no observer modeling)."""
    return "denial" if internal_state == "missed" else "vague"


def level1_action(internal_state: str) -> str:
    """Level 1: the observer is modeled as level 0 (face-value reading).

    For an honest player (goal: be accurate) the truthful announcement is
    optimal under a face-value observer, so level 1 reproduces level 0.
    """
    return level0_action(internal_state)


def level3_action(internal_state: str, target_state: str) -> str:
    """Level 3: the observer is modeled as level 1 (belief-forming).

    Deliberately pick the announcement that induces the target belief.
    The face-value map makes ``denial`` the unique strongest inducer of the
    "missed" belief, so a strategic player hiding a noticed state says
    exactly what a genuine player who missed would say (mimicry).
    """
    best, best_score = None, None
    for action in ACTIONS:
        score = FACE_VALUE_BELIEF[action][target_state]
        if best is None or score > best_score:
            best, best_score = action, score
    if best is None:
        raise InstanceConstructionError("level-3 policy produced no action")
    return best


def verify_mimicry_invariant(level1_action_taken: str, level3_action_taken: str) -> None:
    """The level-3 player must reproduce the level-1 player's announcement.

    This is what makes the paired worlds observationally equivalent in the
    non-identifiable regime. It is checked on every built instance.
    """
    if level1_action_taken != level3_action_taken:
        raise InstanceConstructionError(
            "mimicry invariant violated: level-3 action "
            f"{level3_action_taken!r} != level-1 action {level1_action_taken!r}"
        )


